import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const bank = JSON.parse(await readFile(new URL('../data/questions.json', import.meta.url), 'utf8'));
const artifacts = fileURLToPath(new URL('../.artifacts/', import.meta.url));
await mkdir(artifacts, { recursive: true });
const url = process.env.TEST_URL || 'http://localhost:4173/therapy-trainer/';
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || undefined, headless: true });
const failures = [];
const watch = page => {
  page.on('pageerror', error => failures.push(error.message));
  page.on('response', response => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
};
const action = (page, name) => page.locator(`[data-action="${name}"]`);
const choose = async (page, label) => {
  await page.locator('.option').filter({ has: page.locator(`input[data-option="${label}"]`) }).click();
};
const localState = page => page.evaluate(() => JSON.parse(localStorage.getItem('therapy-trainer:v1')));
const assertFits = async page => {
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Horizontal overflow');
};
const setRange = async (page, from, to) => {
  await page.locator('#range-from').fill(String(from));
  await page.locator('#range-to').fill(String(to));
};
const currentQuestion = page => page.locator('.question-number').textContent();

try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage();
  watch(page);
  await page.goto(url);
  await page.locator('#start-heading').waitFor();
  await assertFits(page);
  await page.screenshot({ path: `${artifacts}/desktop-home.png`, fullPage: true });
  await setRange(page, 40, 20);
  assert.equal(await action(page, 'start').isDisabled(), true);
  assert.equal(await page.locator('#range-error').isVisible(), true);
  await setRange(page, 1, 3);
  await action(page, 'start').click();
  assert.match(await currentQuestion(page), /№1$/);
  assert.deepEqual(await page.locator('.option-letter').allTextContents(), ['А', 'Б', 'В', 'Г', 'Д']);
  await choose(page, 'а');
  await action(page, 'primary').click();
  await page.locator('.feedback.wrong').waitFor();
  assert.match(await page.locator('.feedback').textContent(), /Правильный ответ: Б\)/);
  await action(page, 'primary').click();
  assert.match(await currentQuestion(page), /№2$/);
  await choose(page, 'б');
  await action(page, 'primary').click();
  await action(page, 'home').first().click();
  await page.reload();
  await action(page, 'resume').waitFor();
  await action(page, 'resume').click();
  assert.match(await currentQuestion(page), /№2$/);
  assert.equal((await localState(page)).stats[2].attempts, 1);
  await action(page, 'primary').click();
  assert.match(await currentQuestion(page), /№3$/);
  await choose(page, 'г');
  await action(page, 'primary').click();
  await action(page, 'primary').click();
  await page.locator('.result-score').waitFor();
  assert.match(await page.locator('.result-score').textContent(), /67%/);
  assert.equal(await page.locator('.review-item').count(), 1);
  await action(page, 'result-mistakes').click();
  assert.match(await currentQuestion(page), /№1$/);
  await choose(page, 'б');
  await action(page, 'primary').click();
  await action(page, 'primary').click();
  await action(page, 'home').first().click();
  assert.equal(await action(page, 'mistakes').isDisabled(), true);
  await action(page, 'settings').click();
  const downloaded = page.waitForEvent('download');
  await action(page, 'export').click();
  const download = await downloaded;
  const backupPath = `${artifacts}/progress-backup.json`;
  await download.saveAs(backupPath);
  const backup = JSON.parse(await readFile(backupPath, 'utf8'));
  assert.equal(Object.keys(backup.stats).length, 3);
  assert.equal(backup.stats[1].attempts, 2);
  await action(page, 'reset').click();
  await action(page, 'confirm-modal').click();
  assert.equal(Object.keys((await localState(page)).stats).length, 0);
  await page.locator('#import-file').setInputFiles(backupPath);
  await action(page, 'confirm-modal').waitFor();
  await action(page, 'confirm-modal').click();
  assert.equal(Object.keys((await localState(page)).stats).length, 3);
  console.log('PASS learning, ordered navigation, resume, mistakes, backup, import, reset');

  await page.locator('[data-mode="exam"]').click();
  await setRange(page, 96, 98);
  await action(page, 'start').click();
  await choose(page, bank.questions[95].answer);
  assert.equal(await page.locator('.feedback, .option.correct, .option.incorrect').count(), 0);
  assert.equal(Object.keys((await localState(page)).stats).length, 3);
  await action(page, 'primary').click();
  await choose(page, bank.questions[96].answer);
  await page.reload();
  await page.locator('.question-number').waitFor();
  assert.match(await currentQuestion(page), /№97$/);
  assert.equal(await page.locator('input:checked').getAttribute('value'), bank.questions[96].answer);
  await action(page, 'primary').click();
  assert.match(await currentQuestion(page), /№98$/);
  await action(page, 'primary').click();
  await action(page, 'confirm-modal').click();
  await page.locator('.result-score').waitFor();
  assert.match(await page.locator('.result-score').textContent(), /67%/);
  assert.equal((await localState(page)).stats[98].lastAnswer, null);
  const attempts = (await localState(page)).stats[96].attempts;
  await page.reload();
  await page.locator('.result-score').waitFor();
  assert.equal((await localState(page)).stats[96].attempts, attempts);
  await action(page, 'toggle-review').click();
  assert.equal(await page.locator('.review-item').count(), 3);
  await page.screenshot({ path: `${artifacts}/desktop-result.png`, fullPage: true });
  console.log('PASS exam hides feedback, restores selections, grades skipped questions, prevents double scoring');

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const phone = await mobile.newPage();
  watch(phone);
  await phone.goto(url);
  await phone.locator('#start-heading').waitFor();
  await assertFits(phone);
  await phone.screenshot({ path: `${artifacts}/mobile-home.png`, fullPage: true });
  await setRange(phone, 398, 400);
  await action(phone, 'start').click();
  assert.match(await currentQuestion(phone), /№398$/);
  assert.deepEqual(await phone.locator('.option-letter').allTextContents(), ['А', 'Б', 'В', 'Г']);
  await choose(phone, 'в');
  await action(phone, 'primary').click();
  await assertFits(phone);
  await phone.evaluate(() => window.scrollTo(0, 0));
  await phone.screenshot({ path: `${artifacts}/mobile-question.png`, fullPage: true });
  await phone.setViewportSize({ width: 320, height: 740 });
  await assertFits(phone);
  await action(phone, 'home').first().click();
  await assertFits(phone);
  await action(phone, 'resume').click();
  await action(phone, 'question-nav').last().click();
  assert.deepEqual(await phone.locator('.question-dot').allTextContents(), ['398', '399', '400']);
  await phone.locator('[data-action="jump"][data-index="2"]').click();
  assert.match(await currentQuestion(phone), /№400$/);
  await phone.setViewportSize({ width: 768, height: 1024 });
  await assertFits(phone);
  await phone.screenshot({ path: `${artifacts}/tablet-question.png`, fullPage: true });
  console.log('PASS mobile 390px/320px, tablet 768px, original option order, jump navigation');

  const denied = await browser.newContext();
  await denied.addInitScript(() => {
    Storage.prototype.setItem = function () { throw new DOMException('Blocked', 'SecurityError'); };
  });
  const blocked = await denied.newPage();
  watch(blocked);
  await blocked.goto(url);
  await blocked.locator('#start-heading').waitFor();
  await action(blocked, 'start').click();
  assert.equal(await blocked.locator('#notice').isVisible(), true);
  await choose(blocked, 'б');
  await action(blocked, 'primary').click();
  await blocked.locator('.feedback').waitFor();
  console.log('PASS denied storage keeps training usable and shows persistence warning');

  assert.deepEqual(failures, [], 'Browser errors or broken asset requests');
  await writeFile(`${artifacts}/browser-checks.json`, JSON.stringify({ url, errors: failures, result: 'passed', viewports: [1440, 390, 320, 768] }, null, 2));
  console.log('All browser checks passed.');
} finally {
  await browser.close();
}
